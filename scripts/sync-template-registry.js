const fs = require('fs');
const path = require('path');

function convertToEnumKey(folderName) {
  const digitWords = ['ZERO', 'ONE', 'TWO', 'THREE', 'FOUR', 'FIVE', 'SIX', 'SEVEN', 'EIGHT', 'NINE'];
  
  // Replace each digit with its word representation and a trailing underscore
  let clean = folderName.replace(/[0-9]/g, (match) => {
    return digitWords[parseInt(match, 10)] + '_';
  });

  // Convert to UPPER_SNAKE_CASE:
  clean = clean.toUpperCase()
               .replace(/[^A-Z0-9_]/g, '_') // Replace non-alphanumeric/non-underscore with _
               .replace(/_+/g, '_')         // Merge multiple underscores
               .replace(/^_+|_+$/g, '');     // Trim leading/trailing underscores

  return clean;
}

function run() {
  const templatesDir = path.join(process.cwd(), 'public', 'templates');
  const targetFile = path.join(process.cwd(), 'src', 'types', 'templates.ts');

  if (!fs.existsSync(templatesDir)) {
    console.error(`Error: Templates directory not found at ${templatesDir}`);
    process.exit(1);
  }

  // Read all folders in templatesDir
  const folders = fs.readdirSync(templatesDir, { withFileTypes: true })
    .filter(dirent => dirent.isDirectory())
    .map(dirent => dirent.name)
    .sort();

  console.log(`Found ${folders.length} template folders. Generating enum keys...`);

  const enumEntries = folders.map(folder => {
    const key = convertToEnumKey(folder);
    return `  ${key} = '${folder}',`;
  });

  const content = `// This file is auto-generated by scripts/sync-template-registry.js. Do not edit manually.
export enum MemeTemplateId {
${enumEntries.join('\n')}
}
`;

  const targetDir = path.dirname(targetFile);
  if (!fs.existsSync(targetDir)) {
    fs.mkdirSync(targetDir, { recursive: true });
  }

  fs.writeFileSync(targetFile, content, 'utf8');
  console.log(`✅ Successfully generated/updated ${targetFile}`);
}

run();
